export function Sidebar({ items }: { items: NavItem[] }) {
  const pathname = usePathname();

  // Categorize navigation items into clean logical clusters
  const academicGroup = items.filter((i) =>
    ["/", "/students", "/attendance", "/homework", "/notes", "/results", "/timetable", "/library"].includes(i.href)
  );
  const operationsGroup = items.filter((i) =>
    ["/transport", "/fees", "/activities", "/announcements"].includes(i.href)
  );
  const adminGroup = items.filter((i) =>
    ["/copilot", "/roles", "/audit"].includes(i.href)
  );

  const renderGroup = (title: string, groupItems: NavItem[]) => {
    if (groupItems.length === 0) return null;
    return (
      <div className="mb-5">
        <div className="px-3 mb-2 text-[10px] font-bold uppercase tracking-widest text-slate-500 font-display">
          {title}
        </div>
        <div className="space-y-1">
          {groupItems.map((item) => {
            const active =
              item.href === "/" ? pathname === "/" : pathname.startsWith(item.href);
            const isAi = item.href === "/copilot";

            return (
              <Link
                key={item.href}
                href={item.href}
                aria-current={active ? "page" : undefined}
                className={`group relative flex items-center gap-3 rounded-xl px-3 py-2.5 text-xs font-semibold transition-all duration-200 ${
                  active
                    ? "bg-gradient-to-r from-brand-600 via-indigo-600 to-indigo-700 text-white shadow-[0_0_20px_-3px_rgba(99,102,241,0.4)] ring-1 ring-white/10"
                    : isAi
                    ? "text-brand-300 bg-brand-500/10 hover:bg-brand-500/20 border border-brand-500/20 font-bold"
                    : "text-slate-400 hover:bg-white/[0.04] hover:text-white"
                }`}
              >
                {active && (
                  <span className="absolute left-1 top-1/2 -translate-y-1/2 h-5 w-1 rounded-full bg-white shadow-sm" />
                )}
                <NavIcon path={item.href} active={active} />
                <span className="flex-1 truncate tracking-tight">{item.label}</span>
                {isAi && (
                  <span className="rounded-full bg-brand-500/20 text-brand-300 px-2 py-0.5 text-[9px] font-mono font-bold uppercase border border-brand-500/30">
                    AI
                  </span>
                )}
              </Link>
            );
          })}
        </div>
      </div>
    );
  };

  return (
    <nav className="flex flex-col p-3.5" aria-label="Main navigation">
      {renderGroup("Academic Operations", academicGroup)}
      {renderGroup("Campus Operations & Finance", operationsGroup)}
      {renderGroup("Staff & System Governance", adminGroup)}
    </nav>
  );
}
